// If-Else Statement
let num = 10;
if (num > 0) {
    console.log("Positive number");
} else {
    console.log("Non-positive number");
}

// Switch Statement
let day = 3;
switch (day) {
    case 1:
        console.log("Monday");
        break;
    case 2:
        console.log("Tuesday");
        break;
    case 3:
        console.log("Wednesday");
        break;
    default:
        console.log("Another day");
}

// For Loop
for (let i = 0; i < 5; i++) {
    console.log("For loop iteration:", i);
}

// While Loop
let count = 0;
while (count < 5) {
    console.log("While loop count:", count);
    count++;
}